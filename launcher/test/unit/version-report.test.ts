/**
 * version-report.test — `mandu version` (version-report.ts; packaging.md
 * §11.7) over a fake host: what each `mandu` on PATH is, which one runs, an
 * npm package's recorded commit against a checkout's live one, and every
 * problem rule with its fix: another mandu first on PATH or behind it,
 * MANDU_DEV_REPO forcing an npm mandu onto a source tree, services of
 * another release (systemd-kept, pinned, or plain), a global npm package
 * that is not the one running, an old Node. Nothing is read from this host.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { Layout } from "../../src/services/layout.js";
import {
  classifyMandu, commitWords, gatherVersionReport, globalNpmRoot, problemsOf, renderVersionReport,
  type VersionDeps, type VersionReport,
} from "../../src/version-report.js";
import { launcherVersion } from "../../src/update-check.js";
import type { StackSupervisor } from "../../src/stack-supervisor.js";
import { stateAxes } from "../axes.js";

stateAxes("secrets"); // no arbiter is built; stated per the suite rule

const OURS = launcherVersion();
const NPM = "/usr/lib/node_modules/@mandusec/mandu";
const REPO = "/home/u/project/mandu";
const S = "5".repeat(40), P = "9".repeat(40);

/** A fake host. `files` = path → contents; `links` = path → real path. */
function host(over: Partial<VersionDeps> & { files?: Record<string, string>; links?: Record<string, string>; exe?: string[] } = {}): VersionDeps {
  const files = over.files ?? {};
  const links = over.links ?? {};
  const exe = new Set(over.exe ?? Object.keys(links));
  const layout = over.layout ?? Layout.installed(NPM);
  return {
    env: { PATH: "/usr/bin" },
    argv1: "/usr/bin/mandu",
    moduleUrl: `file://${NPM}/dist/mandu.mjs`,
    layout,
    realpath: (p) => links[p] ?? (files[p] !== undefined || exe.has(p) ? p : null),
    isExecutable: (p) => exe.has(p),
    exists: (p) => files[p] !== undefined,
    readFile: (p) => files[p] ?? null,
    git: () => null,
    hello: async () => undefined,
    arbiterSock: () => ({ sock: "/run/user/1/mandu/current/arbiter.sock", mode: "current", base: "/run/user/1/mandu" }),
    supervisor: () => null,
    cwdOf: () => null,
    npmRoot: () => null,
    ownBuild: () => ({ bundle: "0123456789abcdef", rev: null }),
    sameArbiterTree: () => null,
    node: { version: "22.13.0", path: "/usr/bin/node" },
    ...over,
  };
}

const NPM_FILES = {
  [`${NPM}/package.json`]: JSON.stringify({ version: OURS }),
  [`${NPM}/dist/build-info.json`]: JSON.stringify({ version: OURS, sourceCommit: S, publicCommit: P, publicAhead: 0, dirty: false }),
};

test("classifyMandu: the npm bin, a checkout's bin, its mandu-run.sh, the bootstrap shim, anything else", () => {
  const files: Record<string, string> = {
    [`${NPM}/package.json`]: JSON.stringify({ version: "0.2.0-beta.6" }),
    [`${REPO}/launcher/package.json`]: JSON.stringify({ version: "0.2.0-beta.5" }),
    [`${REPO}/launcher/src/run.ts`]: "",
    "/home/u/.local/bin/mandu": `#!/usr/bin/env bash\n# Mandu launcher shim (generated by scripts/bootstrap.sh — M1 interim channel).\nREPO_ROOT="${REPO}"\nexec bash "$REPO_ROOT/launcher/mandu-run.sh" "$@"\n`,
    "/opt/bin/mandu": "#!/bin/sh\necho hi\n",
  };
  const d = { exists: (p: string) => files[p] !== undefined, readFile: (p: string) => files[p] ?? null };
  assert.deepEqual(classifyMandu(`${NPM}/bin/mandu.mjs`, d), { kind: "npm", root: NPM, version: "0.2.0-beta.6" });
  assert.deepEqual(classifyMandu(`${REPO}/launcher/bin/mandu.mjs`, d), { kind: "checkout-build", root: REPO, version: "0.2.0-beta.5" });
  assert.deepEqual(classifyMandu(`${REPO}/launcher/mandu-run.sh`, d), { kind: "checkout-shim", root: REPO, version: "0.2.0-beta.5" });
  assert.deepEqual(classifyMandu("/home/u/.local/bin/mandu", d), { kind: "checkout-shim", root: REPO, version: "0.2.0-beta.5" });
  assert.deepEqual(classifyMandu("/opt/bin/mandu", d), { kind: "other", root: null, version: null });
});

test("an npm mandu first on PATH, nothing else: its recorded commits, no problems", async () => {
  const r = await gatherVersionReport(host({ files: NPM_FILES, links: { "/usr/bin/mandu": `${NPM}/bin/mandu.mjs` } }));
  assert.equal(r.self.kind, "npm");
  assert.equal(r.self.root, NPM);
  assert.equal(r.self.realPath, `${NPM}/bin/mandu.mjs`);
  assert.equal(r.self.commitsFrom, "build-info");
  assert.equal(r.self.sourceCommit, S);
  assert.equal(r.self.publicCommit, P);
  assert.deepEqual(r.path.map((e) => [e.path, e.kind, e.running]), [["/usr/bin/mandu", "npm", true]]);
  assert.deepEqual(r.problems, []);
  const text = renderVersionReport(r);
  assert.match(text, new RegExp(`^mandu ${OURS.replace(/\./g, "\\.")}\n`));
  assert.match(text, /commit: +source 555555555555, public 999999999999\n/);
  assert.match(text, /No install problems found\./);
  assert.match(text, /mandu doctor/);
});

test("an npm package built before the record says so, never a guess", async () => {
  const r = await gatherVersionReport(host({ files: { [`${NPM}/package.json`]: "{}" }, links: { "/usr/bin/mandu": `${NPM}/bin/mandu.mjs` } }));
  assert.equal(r.self.commitsFrom, "none");
  assert.match(commitWords(r.self), /not recorded/);
});

test("the incident: an old source checkout's shim behind the npm mandu, its services kept alive by systemd", async () => {
  const sup: StackSupervisor = {
    unit: "mandu-dashboard.service", user: true, mainPid: 100, restart: "always",
    workingDirectory: `${REPO}/dashboard`, fragmentPath: "/home/u/.config/systemd/user/mandu-dashboard.service",
  };
  const r = await gatherVersionReport(host({
    env: { PATH: "/usr/bin:/home/u/.local/bin" },
    files: {
      ...NPM_FILES,
      [`${REPO}/launcher/package.json`]: JSON.stringify({ version: "0.2.0-beta.5" }),
      [`${REPO}/launcher/src/run.ts`]: "",
      "/home/u/.local/bin/mandu": `# Mandu launcher shim (generated by scripts/bootstrap.sh — M1 interim channel).\nREPO_ROOT="${REPO}"\n`,
    },
    links: { "/usr/bin/mandu": `${NPM}/bin/mandu.mjs` },
    exe: ["/usr/bin/mandu", "/home/u/.local/bin/mandu"],
    hello: async () => ({ pid: 4242, protocolVersion: 1, version: "0.2.0-beta.5", startedAt: "2026-10-16T21:45:12.710Z" }),
    supervisor: (base, pid) => (base === "/run/user/1/mandu" && pid === 4242 ? sup : null),
    cwdOf: (pid) => (pid === 4242 ? `${REPO}/launcher` : null),
  }));
  assert.deepEqual(r.path.map((e) => [e.kind, e.running]), [["npm", true], ["checkout-shim", false]]);
  assert.equal(r.services?.verdict, "older");
  assert.equal(r.services?.codeDir, `${REPO}/launcher`);
  const ids = r.problems.map((p) => p.id);
  assert.deepEqual(ids, ["path-shadowed", "services-supervised-other-build"]);
  const svc = r.problems[1]!;
  assert.match(svc.problem, /Mandu 0\.2\.0-beta\.5/);
  assert.match(svc.problem, /running from \/home\/u\/project\/mandu\/launcher/);
  assert.match(svc.problem, /systemd user service mandu-dashboard\.service/);
  assert.match(svc.fix, /^systemctl --user disable --now mandu-dashboard\.service/);
  assert.match(svc.fix, /; or, to keep that service, run this mandu on its own stack: MANDU_HOME=~\/\.mandu-own MANDU_RUNTIME_DIR=\/run\/user\/1\/mandu-own mandu … \(a Mandu folder of its own, [^)]*\)$/);
  assert.match(r.problems[0]!.fix, /rm \/home\/u\/\.local\/bin\/mandu/);
  const text = renderVersionReport(r);
  assert.match(text, /kept alive by: the systemd user service mandu-dashboard\.service/);
  assert.match(text, /ANOTHER RELEASE than this mandu/);
  assert.match(text, /2 problems:/);
});

test("problems: another mandu runs first; MANDU_DEV_REPO forces an npm mandu onto a tree; pinned; plain restartable", async () => {
  const first = await gatherVersionReport(host({
    env: { PATH: "/home/u/.local/bin:/usr/bin" },
    files: { ...NPM_FILES, [`${REPO}/launcher/package.json`]: JSON.stringify({ version: "0.2.0-beta.5" }) },
    links: { "/usr/bin/mandu": `${NPM}/bin/mandu.mjs`, "/home/u/.local/bin/mandu": `${REPO}/launcher/mandu-run.sh` },
  }));
  const run = first.problems.find((p) => p.id === "path-runs-another");
  assert.ok(run, JSON.stringify(first.problems));
  assert.match(run.problem, /typing `mandu` runs \/home\/u\/\.local\/bin\/mandu \(the source checkout \/home\/u\/project\/mandu \(0\.2\.0-beta\.5\)/);
  assert.match(run.fix, /put \/usr\/bin before \/home\/u\/\.local\/bin on PATH/);

  const forced = await gatherVersionReport(host({
    env: { PATH: "/usr/bin", MANDU_DEV_REPO: REPO },
    files: NPM_FILES,
    links: { "/usr/bin/mandu": `${NPM}/bin/mandu.mjs` },
    layout: Layout.dev(REPO, NPM),
  }));
  const f = forced.problems.find((p) => p.id === "forced-dev-layout");
  assert.ok(f, JSON.stringify(forced.problems));
  assert.match(f.problem, /MANDU_DEV_REPO=\/home\/u\/project\/mandu makes this npm mandu start its services from the source tree/);
  assert.match(f.fix, /^unset MANDU_DEV_REPO/);
  assert.equal(forced.env["MANDU_DEV_REPO"], REPO);

  const older = { pid: 7, protocolVersion: 1, version: "0.0.1" };
  const pinned = await gatherVersionReport(host({
    files: NPM_FILES, links: { "/usr/bin/mandu": `${NPM}/bin/mandu.mjs` },
    hello: async () => older,
    arbiterSock: () => ({ sock: "/tmp/x.sock", mode: "pinned", base: "/run/user/1/mandu" }),
  }));
  assert.deepEqual(pinned.problems.map((p) => p.id), ["services-pinned-other-build"]);
  const plain = await gatherVersionReport(host({ files: NPM_FILES, links: { "/usr/bin/mandu": `${NPM}/bin/mandu.mjs` }, hello: async () => older }));
  assert.deepEqual(plain.problems.map((p) => p.id), ["services-other-build"]);
  assert.match(plain.problems[0]!.fix, /mandu stop --stack \/run\/user\/1\/mandu$/);
  // The same release and build: no problem, and the report says it matches.
  const same = await gatherVersionReport(host({
    files: NPM_FILES, links: { "/usr/bin/mandu": `${NPM}/bin/mandu.mjs` },
    hello: async () => ({ pid: 7, protocolVersion: 1, version: OURS, build: { bundle: "0123456789abcdef", rev: null } }),
  }));
  assert.deepEqual(same.problems, []);
  assert.match(renderVersionReport(same), /: same as this mandu/);
  // Another build of this release.
  const build = await gatherVersionReport(host({
    files: NPM_FILES, links: { "/usr/bin/mandu": `${NPM}/bin/mandu.mjs` },
    hello: async () => ({ pid: 7, protocolVersion: 1, version: OURS, build: { bundle: "fedcba9876543210", rev: null } }),
  }));
  assert.equal(build.services?.verdict, "build");
  assert.match(build.problems[0]!.problem, /another build of Mandu .* \(bundle fedcba9876543210; this mandu's is bundle 0123456789abcdef\)/);
});

test("problems: a global npm package that is not the running mandu; an old Node", () => {
  const base: Omit<VersionReport, "problems"> = {
    self: {
      invoked: `${REPO}/launcher/bin/mandu.mjs`, realPath: `${REPO}/launcher/bin/mandu.mjs`, kind: "checkout-build", root: REPO,
      version: "0.2.0-beta.5", commitsFrom: "git", sourceCommit: S, publicCommit: null, publicAhead: 0, dirty: false,
    },
    node: { version: "22.12.0", path: "/usr/bin/node", meetsFloor: false, floor: "22.13.0" },
    path: [],
    services: null,
    env: {},
    npmGlobal: { root: "/usr/lib/node_modules", version: "0.2.0-beta.6", installed: true },
    forcedLayout: null,
  };
  const ids = problemsOf(base).map((p) => p.id);
  assert.deepEqual(ids, ["npm-not-running", "node-too-old"]);
});

test("a checkout reads its commit from git now, not from a recorded file", async () => {
  const r = await gatherVersionReport(host({
    argv1: `${REPO}/launcher/bin/mandu.mjs`,
    moduleUrl: `file://${REPO}/launcher/src/version-report.ts`,
    layout: Layout.dev(REPO),
    files: { [`${REPO}/launcher/src/run.ts`]: "" },
    git: (d, args) => (args[0] === "rev-parse" ? `${d}\n${S}\n` : args[0] === "status" ? " M x\n" : ""),
  }));
  assert.equal(r.self.kind, "checkout-source");
  assert.equal(r.self.root, REPO);
  assert.equal(r.self.commitsFrom, "git");
  assert.equal(commitWords(r.self), "source 555555555555, public not recorded + uncommitted changes");
  assert.equal(r.forcedLayout, null);
});

test("globalNpmRoot: npm_config_prefix, else ~/.npmrc's prefix, else the running node's; npm itself never runs", () => {
  const rc = (text: string | null) => (p: string) => (p === "/home/u/.npmrc" ? text : null);
  assert.equal(globalNpmRoot({ HOME: "/home/u", npm_config_prefix: "/opt/npm" }, "/usr/bin/node", rc("prefix=/x")), "/opt/npm/lib/node_modules");
  assert.equal(globalNpmRoot({ HOME: "/home/u" }, "/usr/bin/node", rc("registry=https://r\nprefix = ~/.npm-global\n")), "/home/u/.npm-global/lib/node_modules");
  assert.equal(globalNpmRoot({ HOME: "/home/u" }, "/usr/bin/node", rc('prefix="${HOME}/g"')), "/home/u/g/lib/node_modules");
  assert.equal(globalNpmRoot({ HOME: "/home/u" }, "/home/u/.nvm/versions/node/v22.13.0/bin/node", rc(null)),
    "/home/u/.nvm/versions/node/v22.13.0/lib/node_modules");
  assert.equal(globalNpmRoot({}, "/usr/bin/node", rc(null)), "/usr/lib/node_modules");
});
