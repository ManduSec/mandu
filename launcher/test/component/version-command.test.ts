/**
 * version-command e2e — `mandu version` through the real CLI entry
 * (version-report.ts; packaging.md §11.7), from this checkout:
 *   - the checkout's live commit (git HEAD), its kind and its root;
 *   - an old from-source install's shim first on PATH (the bootstrap.sh
 *     shape) is named, with what it is and the fix;
 *   - a stand-in arbiter of an older release on a pinned socket: its release
 *     comes from its own `hello` over the socket, and the report says a
 *     launch refuses it;
 *   - `--json` agrees with the text; `--version` stays one line; `--help`
 *     prints the verb's usage. Nothing is started or stopped.
 * The npm side (a packed, installed tarball) is npm-pack.test.ts.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { chmodSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { createServer, type Server } from "node:net";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { runCli } from "../lib/run-cli.js";
import { stateAxes } from "../axes.js";

stateAxes("secrets"); // a stand-in arbiter answers hello only; stated per the suite rule

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

/** A stand-in arbiter that answers `hello` as an older release would. */
function standIn(sock: string, hello: Record<string, unknown>): Promise<Server> {
  const srv = createServer((c) => {
    let buf = "";
    c.setEncoding("utf8").on("data", (d: string) => {
      buf += d;
      const nl = buf.indexOf("\n");
      if (nl < 0) return;
      const req = JSON.parse(buf.slice(0, nl)) as { id: number; op: string };
      c.end(JSON.stringify(req.op === "hello" ? { id: req.id, ok: true, result: hello } : { id: req.id, ok: false, error: "unknown op" }) + "\n");
    });
  });
  return new Promise((resolve) => srv.listen(sock, () => resolve(srv)));
}

test("mandu version from a checkout: its commit, an old shim first on PATH, an older arbiter on the socket", { timeout: 120_000 }, async () => {
  const dir = mkdtempSync(join(tmpdir(), "mdu-version-e2e-"));
  const oldRepo = join(dir, "old-mandu");
  mkdirSync(join(oldRepo, "launcher"), { recursive: true });
  writeFileSync(join(oldRepo, "launcher", "package.json"), JSON.stringify({ version: "0.2.0-beta.3" }));
  const shimDir = join(dir, "bin");
  mkdirSync(shimDir);
  const shim = join(shimDir, "mandu");
  writeFileSync(shim, `#!/usr/bin/env bash\n# Mandu launcher shim (generated by scripts/bootstrap.sh — M1 interim channel).\nset -euo pipefail\nREPO_ROOT="${oldRepo}"\nexec bash "$REPO_ROOT/launcher/mandu-run.sh" "$@"\n`);
  chmodSync(shim, 0o755);
  const sock = join(dir, "arbiter.sock");
  const srv = await standIn(sock, { pid: process.pid, protocolVersion: 1, version: "0.2.0-beta.3", gitRev: "abc1234", gitDirty: false, startedAt: "2026-10-01T00:00:00.000Z" });
  const env = {
    PATH: `${shimDir}:${process.env["PATH"] ?? ""}`,
    HOME: join(dir, "home"),
    MANDU_RUNTIME_DIR: join(dir, "rt"),
    MANDU_ARBITER_SOCK: sock,
    npm_config_prefix: join(dir, "npm-global"),
  };
  try {
    const head = spawnSync("git", ["-C", REPO, "rev-parse", "HEAD"], { encoding: "utf8" }).stdout.trim();
    const j = await runCli(["version", "--json"], env);
    assert.equal(j.code, 0, j.stderr);
    const rep = JSON.parse(j.stdout) as {
      self: { kind: string; root: string; commitsFrom: string; sourceCommit: string; version: string };
      path: Array<{ path: string; kind: string; root: string | null; version: string | null; running: boolean }>;
      services: { running: boolean; version: string; verdict: string; sockMode: string; pid: number };
      env: Record<string, string>;
      problems: Array<{ id: string; problem: string; fix: string }>;
    };
    assert.equal(rep.self.kind, "checkout-source");
    assert.equal(rep.self.commitsFrom, "git");
    assert.equal(rep.self.sourceCommit, head);
    assert.deepEqual(rep.path[0], { path: shim, realPath: shim, kind: "checkout-shim", root: oldRepo, version: "0.2.0-beta.3", running: false });
    assert.equal(rep.services.running, true);
    assert.equal(rep.services.version, "0.2.0-beta.3");
    assert.equal(rep.services.verdict, "older");
    assert.equal(rep.services.sockMode, "pinned");
    assert.equal(rep.env["MANDU_ARBITER_SOCK"], sock);
    const ids = rep.problems.map((p) => p.id);
    assert.ok(ids.includes("path-runs-another"), ids.join(","));
    assert.ok(ids.includes("services-pinned-other-build"), ids.join(","));
    assert.match(rep.problems.find((p) => p.id === "path-runs-another")!.fix, new RegExp(`remove or rename ${shim}`));

    const t = await runCli(["version"], env);
    assert.equal(t.code, 0, t.stderr);
    assert.match(t.stdout, new RegExp(`^mandu ${rep.self.version.replace(/\./g, "\\.")}\n`));
    assert.match(t.stdout, new RegExp(`commit: +source ${head.slice(0, 12)}`));
    assert.match(t.stdout, /arbiter: +Mandu 0\.2\.0-beta\.3: ANOTHER RELEASE than this mandu/);
    assert.match(t.stdout, new RegExp(`the source checkout ${oldRepo} \\(0\\.2\\.0-beta\\.3\\), through its mandu-run\\.sh`));
    assert.match(t.stdout, new RegExp(`${rep.problems.length} problems?:`));

    const one = await runCli(["--version"], env);
    assert.equal(one.stdout, `mandu ${rep.self.version}\n`);
    const help = await runCli(["version", "--help"], env);
    assert.match(help.stdout, /^usage: mandu version \[--json\]/);
  } finally {
    await new Promise<void>((r) => srv.close(() => r()));
    rmSync(dir, { recursive: true, force: true });
  }
});
